-- Jalankan seluruh SQL ini di Supabase > SQL Editor > New query.
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  game text not null check (game in ('Free Fire','Mobile Legends','Roblox')),
  name text not null,
  price bigint not null default 0 check (price >= 0),
  stock boolean not null default true,
  rank text,
  level text,
  items text,
  image text,
  created_at timestamptz not null default now()
);
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  product_name text not null,
  amount bigint not null default 0 check (amount >= 0),
  status text not null default 'Menunggu' check (status in ('Menunggu','Diproses','Selesai','Dibatalkan')),
  note text,
  created_at timestamptz not null default now()
);
create table if not exists public.store_settings (
  key text primary key,
  value text not null
);
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.store_settings enable row level security;

-- Hanya user yang login dapat membaca/mengubah data dashboard.
create policy "Authenticated users manage products" on public.products
for all to authenticated using (true) with check (true);
create policy "Authenticated users manage orders" on public.orders
for all to authenticated using (true) with check (true);
create policy "Authenticated users manage settings" on public.store_settings
for all to authenticated using (true) with check (true);

